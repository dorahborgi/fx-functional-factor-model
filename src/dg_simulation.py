"""
Goal: Simulate data to see how the Grassmann distance behaves if we have a stable loading structure
(i.e. the same subspace generated by the loadings)

H_0: same loading subspace as the 2014 reference period.

The Grassmann distance is computed between subspaces in R^(N*M), so the
simulation must operate in that same space — not in R^N as in the naive approach.

Key idea: C_ref = X X^T / T_ref  where X = Y_ref.reshape(N*M, T_ref)
To draw z ~ N(0, C_ref) without forming C_ref (which is NM×NM):
    eps ~ N(0, I_{T_ref})  →  z = X eps / sqrt(T_ref)

C_ref encodes both common and idiosyncratic variance (full covariance of 2014 data),
so no extra noise term is needed — adding one would double-count idiosyncratic variance.

Parameters:
S = 132 = number of simulated days per sample (≈ 6 months)
B = 1000 = number of Monte Carlo replications

Algorithm:
1. Build centered panel Y_ref (N, T_ref, M) to encode C_ref = X X^T / T_ref
2. Simulate two independent sets of S days in R^(NM) from C_ref
3. Re-estimate loading subspace U1, U2 from each simulated panel
4. Compute d_G(U1, U2)
5. Repeat B times and plot
"""

import numpy as np
import matplotlib.pyplot as plt
import pandas as pd
import os
from scipy import stats as sp_stats


from ffm_fx_real import build_panel_from_matrices, center_panel
from ffm_stability import grassmann_distance, align_signs
from paths import FIGURES_ROOT

os.makedirs(f'{FIGURES_ROOT}/STABILITY', exist_ok=True)


def build_ref_panel(data, start_date, end_date, min_coverage=0.7):
    """
    Build centered panel Y_ref and estimate reference subspace.

    Returns
    -------
    X    : (N*M, T_ref) — encodes C_ref = X X^T / T_ref implicitly
    N, M : panel dimensions, needed to reshape simulated panels
    """
    subsets = {}
    for pair, df in data.items():
        df = df.copy()
        df.index = pd.DatetimeIndex(df.index)
        mask = (df.index >= pd.Timestamp(start_date)) & (df.index <= pd.Timestamp(end_date))
        subsets[pair] = df.loc[mask]

    panel, _, _, _ = build_panel_from_matrices(subsets, min_coverage=min_coverage)
    Y_ref, _   = center_panel(panel)
    N, T_ref, M = Y_ref.shape
    print(f"Reference panel: N={N} pairs, T={T_ref} days, M={M} intervals")

    # X[i*M + τ, t] = Y_ref[i, t, τ]  — same stacking order as empilation_loadings
    X = Y_ref.transpose(1, 0, 2).reshape(T_ref, N * M).T  # (NM, T_ref)

    return X, N, M, Y_ref


def simulate_panel(X, N, M, S=132):
    """
    Simulate S days in R^(N*M) from C_ref = X X^T / T_ref.

    Each column of Z_sim ~ N(0, C_ref) via the identity:
        z = X eps / sqrt(T_ref),  eps ~ N(0, I_{T_ref})

    C_ref already encodes both common and idiosyncratic variance of 2014,
    so no extra noise is added (would double-count idiosyncratic variance).

    Returns Y_sim (N, S, M).
    """
    _, T_ref = X.shape

    eps   = np.random.randn(T_ref, S)
    Z_sim = X @ eps / np.sqrt(T_ref)                     # (NM, S)

    # reshape (NM, S) → (N, S, M) — same stacking order as empilation_loadings
    return Z_sim.reshape(N, M, S).transpose(0, 2, 1)     # (N, S, M)


def estimate_subspace(Y_sim, r=1):
    """
    Return the top-r eigenvectors of C_sim = W_sim^T W_sim / S  in R^(NM).

    Equivalent to running the full FFM pipeline, but direct:
    the top-r right singular vectors of W_sim are exactly the eigenvectors of C_sim,
    which are the loading curves we want — without forming C_sim explicitly.
    """
    N, S, M = Y_sim.shape
    Y_sim = Y_sim - Y_sim.mean(axis=1, keepdims=True) 
    X_sim = Y_sim.transpose(1, 0, 2).reshape(S, N * M).T  # (NM, S)
    U_sim, _, _ = np.linalg.svd(X_sim, full_matrices=False)  # thin SVD
    return U_sim[:, :r]                                    # (NM, r)


def compute_grassmann_distance(U1, U2):
    """
    Align signs of U2 onto U1 and return Grassmann distance.
    """
    U2_aligned = align_signs(U1, U2)
    d, _ = grassmann_distance(U1, U2_aligned)
    return d


def run_simulation_dg(data, start_date, end_date, S=132, B=1000, r=1):
    """
    Simulate null distribution of Grassmann distance in R^(N*M).

    Parameters
    ----------
    data       : dict of DataFrames — intraday vol matrices
    start_date : reference period start
    end_date   : reference period end
    S          : number of simulated days per sample (default 132 ≈ 6 months)
    B          : number of Monte Carlo replications
    r          : number of factors

    Returns
    -------
    list of B Grassmann distances under H0
    """
    # Step 1: build reference panel to encode C_ref
    X, N, M, _ = build_ref_panel(data, start_date, end_date)

    distances = []
    for b in range(B):
        if b % 100 == 0:
            print(f"  Simulation {b}/{B}")

        # Step 2: simulate two independent sets of S days from C_ref
        Y_sim1 = simulate_panel(X, N, M, S)
        Y_sim2 = simulate_panel(X, N, M, S)

        # Step 3: re-estimate loading subspace from each simulated panel
        U1 = estimate_subspace(Y_sim1, r=r)
        U2 = estimate_subspace(Y_sim2, r=r)

        # Step 4: compute Grassmann distance between the two subspaces
        d = compute_grassmann_distance(U1, U2)
        distances.append(d)

    return distances


def plot_simulation_dg(distances, observed=None, figsize=(10, 5)):
    """
    Plot the null distribution of the Grassmann distance.

    Parameters
    ----------
    distances : list or array of simulated d_G values under H0
    observed  : float, optional — observed d_G to compare against the null
    """
    
    s = np.asarray(distances).ravel()
    fig, ax = plt.subplots(figsize=figsize)

    ax.hist(s, bins=40, density=True, alpha=0.50, color='steelblue',
            edgecolor='white', label='Simulated $d_G$ under $H_0$')

    xs = np.linspace(s.min(), s.max(), 400)
    kde = sp_stats.gaussian_kde(s)
    ax.plot(xs, kde(xs), color='steelblue', lw=2, label='KDE')

    mu, sigma = s.mean(), s.std()
    ax.plot(xs, sp_stats.norm.pdf(xs, mu, sigma),
            color='tomato', lw=1.5, linestyle='--',
            label=f'Normal fit  μ={mu:.3f}, σ={sigma:.3f}')

    p95 = np.percentile(s, 95)
    ax.axvline(p95, color='darkorange', lw=1.5, linestyle='--',
               label=f'p95 = {p95:.3f}')
    ax.axvline(mu,  color='grey',       lw=1,   linestyle=':')

    if observed is not None:
        pval = (s >= observed).mean()
        ax.axvline(observed, color='black', lw=2,
                   label=f'Observed = {observed:.3f}  (p = {pval:.3f})')

    ax.set_title('Null distribution of Grassmann distance under $H_0$\n'
                 '(two independent samples of size $S$ from $C_{\\mathrm{ref}}$)',
                 fontsize=12)
    ax.set_xlabel('Grassmann distance $d_G$')
    ax.set_ylabel('Density')
    ax.legend(fontsize=9)
    ax.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(f'{FIGURES_ROOT}/STABILITY/dg_simulation_null.png', dpi=180)
    plt.show()

def circular_block_resample(Y_ref, S=132, block_length = 5):
    """
    Resample S days from Y_ref using circular block bootstrap.

    Parameters
    ----------
    Y_ref        : (N, T_ref, M) — reference panel to resample from
    S            : number of days to resample
    block_length : length of blocks in days

    Returns
    -------
    Y_resampled : (N, S, M) — resampled panel
    """
    N, T_ref, M = Y_ref.shape
    n_blocks = int(np.ceil(S / block_length))
    start_points = np.random.randint(0, T_ref, size=n_blocks)
    
    blocks = []
    for start in start_points:
        end = (start + block_length) % T_ref
        if end > start:
            blocks.append(Y_ref[:, start:end, :])
        else:
            blocks.append(np.concatenate((Y_ref[:, start:, :], Y_ref[:, :end, :]), axis=1))
    
    Y_resampled = np.concatenate(blocks, axis=1)[:, :S, :]
    return Y_resampled

def run_bootstrap_dg(data, start_date, end_date, S=132, B=1000, r=1, block_length=5):
    """
    Simulate null distribution of Grassmann distance using circular block bootstrap.

    Parameters
    ----------
    data         : dict of DataFrames — intraday vol matrices
    start_date   : reference period start
    end_date     : reference period end
    S            : number of days to resample per sample (default 132 ≈ 6 months)
    B            : number of Monte Carlo replications
    r            : number of factors
    block_length : length of blocks in days for circular block bootstrap

    Returns
    -------
    distances : list of simulated d_G values under H0
    """
    # Step 1: build reference panel to encode C_ref
    X, N, M, Y_ref = build_ref_panel(data, start_date, end_date)

    distances = []
    for b in range(B):
        if b % 100 == 0:
            print(f"  Bootstrap {b}/{B}")

        # Step 2: resample two independent sets of S days from Y_ref using circular block bootstrap
        Y_boot1 = circular_block_resample(Y_ref, S=S, block_length=block_length)
        Y_boot2 = circular_block_resample(Y_ref, S=S, block_length=block_length)

        # Step 3: re-estimate loading subspace from each resampled panel
        U1 = estimate_subspace(Y_boot1, r=r)
        U2 = estimate_subspace(Y_boot2, r=r)

        # Step 4: compute Grassmann distance between the two subspaces
        d = compute_grassmann_distance(U1, U2)
        distances.append(d)

    return distances


